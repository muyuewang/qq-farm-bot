export function friendlyActivityError(error: unknown): string {
  if (!error)
    return '操作失败，请稍后重试'
  const message = typeof error === 'string' ? error : (error as Error)?.message || String(error)
  const codeMatch = message.match(/(\d{6})/)
  if (codeMatch?.[1]) {
    const matched = ACTIVITY_ERROR_MAP[codeMatch[1]]
    if (matched)
      return matched
  }
  for (const msg of Object.values(ACTIVITY_ERROR_MAP)) {
    if (message.includes(msg))
      return msg
  }
  return message || '操作失败，请稍后重试'
}
